#!/usr/bin/env python3
"""Render cloudflare/wrangler.template.jsonc -> cloudflare/wrangler.jsonc from env.

"""
import json
import os
import sys

src, dst = sys.argv[1], sys.argv[2]
name = os.environ["WORKER_NAME"]
dom = os.environ.get("CUSTOM_DOMAIN", "").strip()
acct = os.environ.get("CLOUDFLARE_ACCOUNT_ID", "").strip()

out = []
for line in open(src).read().splitlines():
    if line.lstrip().startswith('"account_id"') and not acct:
        continue  # let wrangler login / CLOUDFLARE_ACCOUNT_ID env decide
    out.append(line)
t = "\n".join(out) + "\n"
routes = [{"pattern": dom, "custom_domain": True}] if dom else []
t = (
    t.replace("__WORKER_NAME__", name)
    .replace("__ACCOUNT_ID__", acct)
    .replace("__WORKERS_DEV__", "false" if dom else "true")
    .replace("__ROUTES__", json.dumps(routes))
)
with open(dst, "w") as f:
    f.write("// GENERATED by scripts/deploy-cloudflare.sh from wrangler.template.jsonc - do not commit.\n")
    f.write(t)
